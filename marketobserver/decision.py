def _fmt(value: float, decimals: int) -> str:
    if not value:
        return "n/a"
    return f"{value:,.{decimals}f}"


def render(decision: StrictDecision, lang: str = "en", verbose: bool = False) -> str:
    """Render the strict block. ``lang`` is ``en``, ``ar`` or ``both``."""
    text = _render_ar(decision, verbose) if lang == "ar" else _render_en(decision, verbose)
    if lang == "both":
        return _render_en(decision, verbose) + "\n\n" + "—" * 18 + "\n\n" + _render_ar(decision, verbose)
    return text


