@dataclass(frozen=True)
class Step:
    """One gate of the chain, with the numbers that decided it.

    ``reached`` is False for the gates behind the first failure: the chain stops
    there, so those gates were never a reason for the verdict.
    """

    number: int
    key: str
    title: str
    passed: bool
    detail: str
    numbers: dict = field(default_factory=dict)
    reached: bool = True

    @property
    def state(self) -> str:
        return "pass" if self.passed else ("fail" if self.reached else "stopped")


@dataclass(frozen=True)
class LiquidityTarget:
    kind: str
    price: float
    distance_pct: float
    direction: str  # up | down


@dataclass(frozen=True)
class IndicatorRead:
    """RSI / SMA20 / SMA50 / ATR per timeframe.

    Reported as context only. The gate chain is structure, liquidity, volume,
    candles, zone and reward:risk — a moving-average cross is never allowed to
    open a trade on its own, so these numbers explain the backdrop, they do not
    vote.
    """

    timeframe: str
    rsi: float
    sma20: float
    sma50: float
    atr: float
    alignment: str  # bullish | bearish | flat
    note: str


