# --------------------------------------------------------------------------- #
# thresholds — every one of them is explicit so a report can be audited
# --------------------------------------------------------------------------- #
RVOL_MIN = 1.0            # step 3: below this the market is "weak" -> WAIT
BREAK_VOLUME_MIN = 1.10   # step 3/4: a break under this multiple is a fake break
MIN_RISK_REWARD = 2.0     # step 7: reward:risk floor on the first target
CONTRA_SPIKE_RATIO = 2.2  # a spike this size against the trade rejects it
CONFIRM_MAX_AGE = 8       # bars: how long a confirmation stays tradeable
ZONE_MAX_AGE = 40         # bars: an order block / gap older than this is stale
ZONE_TOLERANCE_ATR = 1.5  # "price is at the zone" = within 1.5 ATR ...
ZONE_TOLERANCE_PCT = 0.003  # ... or 0.3% of price, whichever is wider

BULLISH_PRINTS = {"engulfing_bullish", "hammer", "inverted_hammer", "morning_star", "piercing_line", "dragonfly_doji"}
BEARISH_PRINTS = {"engulfing_bearish", "shooting_star", "evening_star", "dark_cloud_cover", "gravestone_doji"}
NEUTRAL_PRINTS = {"doji", "inside_bar", "outside_bar"}

ENTRY_TIMEFRAME = "15m"
NO_STAMP = datetime(1, 1, 1, tzinfo=timezone.utc)  # "no confirmation time" sentinel
SETUP_TIMEFRAME = "1h"
TREND_TIMEFRAME = "4h"
TIMEFRAMES = (TREND_TIMEFRAME, SETUP_TIMEFRAME, ENTRY_TIMEFRAME)


