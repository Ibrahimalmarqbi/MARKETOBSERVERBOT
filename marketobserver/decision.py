    confidence: str  # high | medium | low
    reasons: tuple[str, ...]
    flags: tuple[str, ...] = ()
    views: tuple[TimeframeSMC, ...] = ()

    @property
    def failed_steps(self) -> tuple[Step, ...]:
        """The gate that stopped the chain (empty when the trade is confirmed)."""
        return tuple(step for step in self.steps if step.reached and not step.passed)

    @property
    def passed_steps(self) -> tuple[Step, ...]:
        return tuple(step for step in self.steps if step.passed)

    @property
    def stopped_at(self) -> int:
        failed = self.failed_steps
        return failed[0].number if failed else 0

    @property
    def decision_label(self) -> str:
        return {"buy": "BUY", "sell": "SELL", "wait": "WAIT"}[self.decision]


