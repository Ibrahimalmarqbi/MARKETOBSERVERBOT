"""Strict Smart-Money + Price-Action decision engine: **BUY / SELL / WAIT**.

This module is deliberately stricter than :mod:`marketobserver.smc`. It is a
*hard* gate chain evaluated in the order below; it stops at the first failure, so
the output is a single decision plus the exact reason it was refused. Nothing
here is generated by a language model: every number is derived from closed
candles supplied by the caller.

Gate order (each step may end the analysis):

1. **Trend (4H)** — structure must be HH + HL (longs only) or LH + LL (shorts
   only). Anything else is ``WAIT``.
2. **Liquidity map** — equal highs/lows, wick-only sweeps, premium/discount
   positioning and the next resting-liquidity target.
3. **Volume filter (overrides everything)** — ``RVOL < 1.0`` is a weak market
   and means ``WAIT``; a break printed on weak volume is an *invalid break*;
   OBV or a counter-direction volume spike rejects the trade outright.
4. **Structure confirmation** — a BOS or CHoCH that *closed* with the trend on
   15m or 1H, not superseded by an opposing break. Wick-only breaks are sweeps,
   never confirmations; a break on weak volume is a fake break and is ignored.
5. **Candle confirmation** — engulfing / pin bar / star / inside bar aligned
   with the trend; an opposing print on the trigger means ``WAIT``.
6. **Entry zone** — an order block or fair-value gap that price *returns* to
   after the confirmation, and never chased.
7. **Risk management** — stop beyond structure, target at the next liquidity
   level, reward:risk >= 2.0 or ``WAIT``.

Only when every gate passes is the output ``BUY`` (long) or ``SELL`` (short).

RSI, SMA20, SMA50 and ATR are computed on every timeframe and reported as
context. They are deliberately *not* gates: the decision is structural, and a
moving-average cross on its own is exactly the kind of signal this engine is
meant to refuse.
"""

